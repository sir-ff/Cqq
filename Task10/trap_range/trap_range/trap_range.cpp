#include <iostream>

int main() 
{
    setlocale(LC_ALL, "Russian");
    int x = 5;
    std::cout << "x=" << x << ": 0<x<10 = " << (0 < x < 10)
        << ", правильно = " << (x > 0 && x < 10) << '\n';

    x = -5;
    std::cout << "x=" << x << ": 0<x<10 = " << (0 < x < 10)
        << ", правильно = " << (x > 0 && x < 10) << '\n';

    /*
     * Почему при x = -5 запись 0 < x < 10 выдаёт 1:
     * Шаг 1. Сначала проверяется левая часть: 0 < -5. ложь, поэтому 0.
     * Шаг 2. Потом 0 подставляется и сравнивается с десяткой: 0 < 10.
     * Шаг 3. Ноль меньше десяти, поэтому ответ — правда выводится 1.
     */

    return 0;
}
