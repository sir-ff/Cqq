#include <iostream>

/*
 * Почему проверка месяца обязана идти первой:
 * Если убрать проверку месяца и подать, например, месяц 13, программа дойдёт
 * до каскада вычисления максимума дней. Ни одна из веток для 30 дней (4, 6, 9, 11)
 * или февраля (2) не сработает, поэтому сработает финальный else и установит
 * max_days = 31 (будто в 13-м месяце 31 день). При корректном дне (например, 15.13.2026)
 * программа ошибочно выведет «Дата 15.13.2026 корректна», а при дне > 31 напечатает
 * бессмысленное сообщение «Ошибка: в месяце 13 не больше 31 дней».
 */

int main() 
{
    setlocale(LC_ALL, "Russian");
    int d, m, y;
    std::cin >> d >> m >> y;

    // 1. Ранний отказ: проверка месяца
    if (m < 1 || m > 12) {
        std::cout << "Ошибка: месяц от 1 до 12\n";
        return 0;
    }

    // 2. Ранний отказ: проверка нижней границы дня
    if (d < 1) {
        std::cout << "Ошибка: день от 1 и больше\n";
        return 0;
    }

    // 3. Вычисление максимума дней в месяце
    int max_days;
    if (m == 2) {
        bool leap = (y % 4 == 0 && y % 100 != 0) || (y % 400 == 0);
        if (leap) {
            max_days = 29;
        }
        else {
            max_days = 28;
        }
    }
    else if (m == 4 || m == 6 || m == 9 || m == 11) {
        max_days = 30;
    }
    else {
        max_days = 31;
    }

    // 4. Финальная проверка верхней границы дня
    if (d <= max_days) {
        std::cout << "Дата " << d << "." << m << "." << y << " корректна\n";
    }
    else {
        std::cout << "Ошибка: в месяце " << m << " не больше " << max_days << " дней\n";
    }

    return 0;
}
