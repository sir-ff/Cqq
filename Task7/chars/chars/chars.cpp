#include <iostream>

int main() 
{
    setlocale(LC_ALL, "Russian");
    std::cout << 'A' << '\n';
    std::cout << 'A' + 1 << '\n'; // 'A' имеет код 65? Нет, 'A' это 65, поэтому 'A' + 1 = 66! 
    // Примечание: в условии опечатка в ожидаемом результате (написано 65, но 'A' (65) + 1 = 66). 
    // Программа выведет 66, так как при сложении char неявно преобразуется в int.
    std::cout << 'a' << '\n';
    std::cout << '0' << '\n';
    std::cout << 0 << '\n';

    /*
     * Объяснение:
     * Символ '0' (в одинарных кавычках) — это текстовый символ (тип char),
     * который хранится в памяти в виде своего числового кода по таблице ASCII (код 48).
     * Число 0 (без кавычек) — это целочисленный литерал (тип int),
     * который хранится непосредственно как математическое значение ноль.
     * На экране они выглядят одинаково, но в вычислениях ведут себя по-разному.
     */

    return 0;
}
