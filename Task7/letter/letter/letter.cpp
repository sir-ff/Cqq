#include <iostream>

int main() 
{
    setlocale(LC_ALL, "Russian");
    char c;
    std::cout << "Буква: ";
    std::cin >> c;

    char next = c + 1;
    std::cout << "Следующая: " << next << '\n';

    /*
     * Исследование для ввода 'Z':
     * Если ввести 'Z', программа напечатает: Следующая: [
     * Объяснение: В таблице кодировки ASCII заглавные латинские буквы идут подряд
     * с кода 65 ('A') по код 90 ('Z'). Сразу после кода 90 идёт код 91,
     * которому соответствует символ открывающей квадратной скобки '['.
     */

    return 0;
}
