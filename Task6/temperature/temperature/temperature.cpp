#include <iostream>

int main() 
{
    setlocale(LC_ALL, "Russian");
    double celsius, fahrenheit;

    // Прямой пересчёт: Цельсий -> Фаренгейт
    std::cout << "Цельсий: ";
    std::cin >> celsius;
    // Используем 9.0 / 5.0, чтобы деление было дробным, а не целочисленным
    double f_result = celsius * 9.0 / 5.0 + 32.0;
    std::cout << "Фаренгейт: " << f_result << std::endl;

    // Обратный пересчёт: Фаренгейт -> Цельсий
    std::cout << "Фаренгейт: ";
    std::cin >> fahrenheit;
    // Из-за особенностей хранения чисел с плавающей точкой (double) в двоичном виде
    // при обратном счёте может появиться незначительный «хвост» погрешности (например, 36.600000000000005),
    // который скрывается при стандартном выводе cout (до 6 значащих цифр).
    double c_result = (fahrenheit - 32.0) * 5.0 / 9.0;
    std::cout << "Цельсий: " << c_result << std::endl;

    // Намеренная порча формулы через целочисленный масштаб
    // В C++ деление двух целых чисел (9 / 5) отбрасывает дробную часть, поэтому scale становится равен 1 вместо 1.8.
    // В итоге формула превращается в (celsius * 1 + 32), то есть 36.6 + 32 = 68.6.
    int scale = 9 / 5;
    double broken_f = celsius * scale + 32.0;
    std::cout << "Испорченная прямая формула: " << broken_f << std::endl;

    return 0;
}

