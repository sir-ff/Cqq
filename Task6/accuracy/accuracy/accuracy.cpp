#include <iostream>

int main() 
{
    setlocale(LC_ALL, "Russian");
    // 1. Печатаем сумму 0.1 + 0.2
    // Выведет 0.3, так как стандартный cout округляет вывод до 6 значащих цифр, скрывая погрешность.
    std::cout << "Сумма: " << 0.1 + 0.2 << std::endl;

    // 2. Сравниваем (0.1 + 0.2 == 0.3)
    // Выведет 0 (false). В двоичной системе числа 0.1, 0.2 и 0.3 являются бесконечными дробями
    // и хранятся с микроскопической погрешностью (0.1 + 0.2 = 0.3000000000000000444...), поэтому точное равенство не выполняется.
    std::cout << "Сумма равна 0.3? " << (0.1 + 0.2 == 0.3) << std::endl;

    // 3. Делим 1.0 / 3.0
    // По умолчанию cout выводит 6 значащих цифр (0.333333). Остальной «хвост» бесконечной дроби
    // не виден, так как стандартная точность потока вывода ограничена 6 знаками (для изменения нужен std::setprecision).
    std::cout << "Треть: " << 1.0 / 3.0 << std::endl;

    return 0;
}

