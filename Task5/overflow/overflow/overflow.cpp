#include <iostream>

int main() 
{
    setlocale(LC_ALL, "Rus");
    int x = 2147483647;

    std::cout << "Было: " << x << "\n";
    std::cout << "Стало: " << x + 1 << "\n";
    std::cout << "Удвоенное: " << x * 2 << "\n";

    /*
     * Объяснение результатов:
     * 1. При прибавлении 1 происходит знаковое переполнение: старший бит
     *    меняется с 0 на 1, и число заворачивается в минимальное отрицательное -2147483648.
     * 2. Умножение на 2 в двоичном виде равносильно сдвигу влево на 1 бит:
     *    в 32 младших битах остаются все единицы, кроме младшего нуля 1111...1110,
     *    что в дополнительном коде соответствует числу -2.
     */
}
